"""Helpers for turning reference results into MoonBit source.

The generated files live next to the tests that read them and carry the `_test`
suffix, so the library build never sees them: only `moon test` compiles them.
"""

import io
import os

HEADER = """// Generated by {script} from {source}. Do not edit: change the script and run it
// again.
"""


def number(value):
    """A MoonBit double literal that reads back as the same double."""
    if value != value:
        raise ValueError("no NaN in a vector")
    text = repr(float(value))
    if "e" in text or "E" in text:
        mantissa, exponent = text.split("e")
        if "." not in mantissa:
            mantissa += ".0"
        return "%se%d" % (mantissa, int(exponent))
    if "." not in text:
        text += ".0"
    return text


def array(values):
    return "[" + ", ".join(number(v) for v in values) + "]"


def write(path, text):
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("wrote %s (%d bytes)" % (path, len(text)))


def bundle(script, source, body):
    return HEADER.format(script=script, source=source) + body
